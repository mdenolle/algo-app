#!/usr/bin/env node
// Turns the verified catalog into the brick shapes the designer builds with:
// footprint in studs, height in plates (a brick is 3 plates), and what the piece
// is for. Parts with no stud footprint (wheels, axles, pins, tyres) are left out:
// the designer places only studded bricks on a stud grid.
//
//   npm run designer:parts   →  designer/parts.generated.js

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = new URL('.', import.meta.url).pathname;
const root = join(here, '..');
const catalog = JSON.parse(readFileSync(join(here, 'catalog.json'), 'utf8'));

const PLATES_PER_BRICK = 3;

/** What a part is, from its official name: this decides its height and how it can be used. */
function classify(part) {
  const name = part.name;
  if (/^Plate/.test(name)) return { kind: 'plate', height: 1 };
  if (/^Tile/.test(name)) return { kind: 'tile', height: 1 };
  if (/^Brick Sloped/.test(name)) return { kind: 'slope', height: PLATES_PER_BRICK };
  if (/^Brick Curved/.test(name)) return { kind: 'curve', height: /2\/3/.test(name) ? 2 : PLATES_PER_BRICK };
  if (/^Brick Arch/.test(name)) return { kind: 'arch', height: PLATES_PER_BRICK * 2 };
  if (/^Brick Round/.test(name)) return { kind: 'round', height: PLATES_PER_BRICK };
  if (/^Brick/.test(name)) return { kind: 'brick', height: PLATES_PER_BRICK };
  return null;
}

const parts = catalog.parts.map(part => {
  const shape = classify(part);
  if (!shape) return null;
  const size = (part.size ?? []).map(Number).filter(n => Number.isFinite(n) && n > 0);
  if (size.length < 2) return null;
  const [a, b] = size;
  if (a > 8 || b > 8) return null;                 // nothing bigger than an 8-stud brick
  return {
    partNum: part.partNum,
    name: part.name,
    kind: shape.kind,
    // Footprint in studs, width × depth; the designer may rotate it 90°.
    footprint: [Math.min(a, b), Math.max(a, b)],
    height: shape.height,                           // in plates
    studs: shape.kind === 'tile' || /No Studs/.test(part.name) ? 0 : Math.min(a, b) * Math.max(a, b),
    colors: part.colors,
  };
}).filter(Boolean);

const json = JSON.stringify(parts, null, 2);
writeFileSync(join(root, 'designer', 'parts.generated.js'),
`// Generated by catalog/designer-parts.mjs from catalog/catalog.json. Do not edit.
// The brick shapes Algo designs with: real part numbers, official names, stud
// footprints and heights in plates (a brick is ${PLATES_PER_BRICK} plates tall).
export const PLATES_PER_BRICK = ${PLATES_PER_BRICK};
export const PARTS = ${json};
export const PART_BY_NUM = Object.fromEntries(PARTS.map(p => [p.partNum, p]));
`);

// Colours, so a design can be drawn in the real LEGO shade and name its pieces.
writeFileSync(join(root, 'designer', 'colors.generated.js'),
`// Generated by catalog/designer-parts.mjs. Do not edit.
export const COLORS = ${JSON.stringify(catalog.colors.map(c => ({ id: c.id, name: c.name, kid: c.kid, rgb: c.rgb, transparent: c.transparent })), null, 2)};
export const COLOR_BY_ID = Object.fromEntries(COLORS.map(c => [c.id, c]));
`);

const byKind = {};
for (const p of parts) byKind[p.kind] = (byKind[p.kind] ?? 0) + 1;
console.log(`${parts.length} buildable shapes:`, Object.entries(byKind).map(([k, n]) => `${n} ${k}`).join(', '));
