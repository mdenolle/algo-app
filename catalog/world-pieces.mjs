#!/usr/bin/env node
// Picks the real LEGO piece each Algo World block is made of, and writes
// world/src/pieces.generated.js. Every block gets a part that LEGO actually
// produced in that block's colour: the catalog's element id proves it.
//
//   npm run world:pieces
//
// A world block is one cube the size of a 2 x 2 brick, so the default part is
// 3003 (Brick 2 x 2). Where LEGO never made 3003 in a colour, the next most
// brick-like part in the catalog that exists in that colour is used instead.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = new URL('.', import.meta.url).pathname;
const root = join(here, '..');
const catalog = JSON.parse(readFileSync(join(here, 'catalog.json'), 'utf8'));
const materialsSource = readFileSync(join(root, 'world', 'src', 'materials.js'), 'utf8');

// Preference order: a 2 x 2 brick if it exists, then other bricks, then plates.
const PREFERRED = ['3003', '3002', '3001', '3941', '3005', '3004', '3062b', '3022', '3020', '3024', '3023'];

const materials = [...materialsSource.matchAll(/id: (\d+), key: '([a-z]+)', name: '([^']+)', lego: \{ id: (\d+), name: '([^']+)' \}/g)]
  .map(m => ({ id: Number(m[1]), key: m[2], name: m[3], colorId: Number(m[4]), colorName: m[5] }));

const colorById = new Map(catalog.colors.map(c => [c.id, c]));
const errors = [];

const pieces = materials.map(material => {
  const color = colorById.get(material.colorId);
  if (!color) { errors.push(`${material.key}: colour ${material.colorId} (${material.colorName}) is not in the catalog; add it to catalog/curated.json`); return null; }
  if (color.name !== material.colorName) errors.push(`${material.key}: colour ${material.colorId} is "${color.name}" in the catalog, not "${material.colorName}"`);
  const available = catalog.parts.filter(part => part.elements[String(material.colorId)]);
  const part = PREFERRED.map(num => available.find(p => p.partNum === num)).find(Boolean) ?? available[0];
  if (!part) { errors.push(`${material.key}: the catalog has no part in ${color.name}`); return null; }
  return {
    material: material.id,
    key: material.key,
    partNum: part.partNum,
    partName: part.name,
    studs: part.size && part.size.length >= 2 ? [Number(part.size[0]), Number(part.size[1])] : [2, 2],
    colorId: color.id,
    colorName: color.name,
    elementId: part.elements[String(material.colorId)],
  };
}).filter(Boolean);

if (errors.length) { console.error('World pieces failed:\n  ' + errors.join('\n  ')); process.exit(1); }

const json = JSON.stringify(pieces, null, 2);
writeFileSync(join(root, 'world', 'src', 'pieces.generated.js'),
`// Generated by catalog/world-pieces.mjs from catalog/catalog.json. Do not edit.
// The real LEGO piece each block in Algo World is made of: part number, official
// part name, official colour, and the element id that proves LEGO made that
// part in that colour. Source: Rebrickable (see catalog/README.md).
export const PIECES = ${json};

export const PIECE_BY_MATERIAL = Object.fromEntries(PIECES.map(p => [p.material, p]));
`);

const swapped = pieces.filter(p => p.partNum !== '3003');
console.log(`${pieces.length} blocks mapped to real LEGO pieces (${pieces.length - swapped.length} × Brick 2 x 2)`);
for (const p of swapped) console.log(`  ${p.key}: ${p.partName} (${p.partNum}) in ${p.colorName} — LEGO never made 3003 in that colour`);
